export function relLabel(key: string): [string, string] {
  if (REL[key]) return REL[key];
  const base = key.replace(/^(true-)/, '').replace(/-/g, ' ');
  if (/^sons-(sons-)+son$/.test(key)) return ["Son's son's son…", 'پڑپوتا'];
  if (/^sons-(sons-)+daughter$/.test(key)) return ["Son's son's daughter…", 'پڑپوتی'];
  if (/grandfather/.test(key)) return [base.replace(/^\w/, (c) => c.toUpperCase()), 'دادا / پردادا'];
  if (/grandmother/.test(key)) return [base.replace(/^\w/, (c) => c.toUpperCase()), 'دادی / نانی'];
  return [base.replace(/^\w/, (c) => c.toUpperCase()), ''];
}

